#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(scriptDir, '..');
const checkOnly = process.argv.includes('--check');

const jsonTargets = [
  'packages/extension/package.json',
  'packages/server/package.json',
  'packages/extension/public/manifest.json',
];

const generatedTargets = [
  'packages/extension/src/product-version.generated.ts',
  'packages/server/src/product-version.generated.ts',
];

function readJson(relativePath) {
  return JSON.parse(fs.readFileSync(path.join(repoRoot, relativePath), 'utf8'));
}

function writeIfChanged(relativePath, content) {
  const targetPath = path.join(repoRoot, relativePath);
  const current = fs.existsSync(targetPath) ? fs.readFileSync(targetPath, 'utf8') : undefined;
  if (current === content) return false;
  fs.writeFileSync(targetPath, content);
  return true;
}

function assertChromeCompatibleVersion(version) {
  const parts = version.split('.');
  const isValid =
    parts.length === 3 &&
    parts.every((part) => /^(0|[1-9]\d*)$/.test(part) && Number(part) <= 65535) &&
    Number(parts[0]) > 0;

  if (!isValid) {
    throw new Error(
      `Product version "${version}" must use Chrome-compatible major.minor.patch integers between 0 and 65535.`,
    );
  }
}

function generatedModule(version) {
  return `// Generated by scripts/sync-product-version.mjs. Do not edit manually.\nexport const PRODUCT_VERSION = '${version}' as const;\n`;
}

const rootPackage = readJson('package.json');
const productVersion = rootPackage.version;
assertChromeCompatibleVersion(productVersion);

const mismatches = [];
for (const relativePath of jsonTargets) {
  const value = readJson(relativePath).version;
  if (value !== productVersion) mismatches.push(`${relativePath} (${value ?? 'missing'})`);
}

for (const relativePath of generatedTargets) {
  const targetPath = path.join(repoRoot, relativePath);
  const expected = generatedModule(productVersion);
  const current = fs.existsSync(targetPath) ? fs.readFileSync(targetPath, 'utf8') : undefined;
  if (current !== expected) mismatches.push(`${relativePath} (stale or missing)`);
}

if (checkOnly) {
  if (mismatches.length > 0) {
    console.error(`Product version ${productVersion} is not synchronized:`);
    mismatches.forEach((mismatch) => console.error(`- ${mismatch}`));
    console.error('Run: pnpm version:sync');
    process.exitCode = 1;
  } else {
    console.log(`Product version ${productVersion} is synchronized.`);
  }
} else {
  const updated = [];
  for (const relativePath of jsonTargets) {
    const manifest = readJson(relativePath);
    manifest.version = productVersion;
    if (writeIfChanged(relativePath, `${JSON.stringify(manifest, null, 2)}\n`)) {
      updated.push(relativePath);
    }
  }

  for (const relativePath of generatedTargets) {
    if (writeIfChanged(relativePath, generatedModule(productVersion))) {
      updated.push(relativePath);
    }
  }

  console.log(
    updated.length > 0
      ? `Synchronized product version ${productVersion}: ${updated.join(', ')}`
      : `Product version ${productVersion} is already synchronized.`,
  );
}
