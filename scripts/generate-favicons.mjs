#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { resolveBuildProfile } from './build-profile.mjs';

const require = createRequire(new URL('../packages/marketing/package.json', import.meta.url));
const sharp = require('sharp');
const profile = resolveBuildProfile();
const brandRoot = pathToFileURL(profile.brandRoot + '/');

// Preserve the Paperbird artwork. Only crop its surrounding transparent canvas,
// scale proportionally, and center. Ignore faint export noise when locating the
// artwork, but keep every original pixel inside the crop (no alpha thresholding).
export async function generateFavicons(checkOnly = false) {
  if (checkOnly) return checkFavicons();
  const source = await readFile(
    new URL(profile.official ? 'paperbird-master.png' : 'library-master.png', brandRoot)
  );
  const { data, info } = await sharp(source)
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  let left = info.width,
    top = info.height,
    right = -1,
    bottom = -1;
  for (let y = 0; y < info.height; y++) {
    for (let x = 0; x < info.width; x++) {
      if (data[(y * info.width + x) * 4 + 3] < 32) continue;
      left = Math.min(left, x);
      top = Math.min(top, y);
      right = Math.max(right, x);
      bottom = Math.max(bottom, y);
    }
  }
  if (right < left) throw new Error('Paperbird master has no visible artwork');
  left = Math.max(0, left - 2);
  top = Math.max(0, top - 2);
  right = Math.min(info.width - 1, right + 2);
  bottom = Math.min(info.height - 1, bottom + 2);
  const crop = { left, top, width: right - left + 1, height: bottom - top + 1 };
  const outputs = new Map();
  for (const size of [16, 32, 48, 64]) {
    const margin = size / 16; // 87.5% inner canvas; even, whole-pixel outer margins.
    const png = await sharp(source)
      .extract(crop)
      .resize(size - margin * 2, size - margin * 2, {
        fit: 'contain',
        background: '#00000000',
        kernel: 'lanczos3',
      })
      .extend({ top: margin, bottom: margin, left: margin, right: margin, background: '#00000000' })
      .png()
      .toBuffer();
    outputs.set(`favicon-${size}x${size}.png`, png);
  }
  const sizes = [16, 32, 48];
  const header = Buffer.alloc(6 + 16 * sizes.length);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(sizes.length, 4);
  let offset = header.length;
  const frames = sizes.map((size, i) => {
    const frame = outputs.get(`favicon-${size}x${size}.png`);
    const entry = 6 + 16 * i;
    header[entry] = size;
    header[entry + 1] = size;
    header.writeUInt16LE(1, entry + 4);
    header.writeUInt16LE(32, entry + 6);
    header.writeUInt32LE(frame.length, entry + 8);
    header.writeUInt32LE(offset, entry + 12);
    offset += frame.length;
    return frame;
  });
  outputs.set('favicon.ico', Buffer.concat([header, ...frames]));
  for (const [name, png] of outputs) {
    await writeFile(new URL(`favicon/${name}`, brandRoot), png);
  }
}

// Resampling and PNG encoding differ across platforms (libvips SIMD paths, zlib),
// so --check cannot compare regenerated bytes. Instead, validate the committed
// outputs structurally: exact PNG dimensions, and an ICO whose frames are
// byte-identical to the committed 16/32/48px PNGs.
async function checkFavicons() {
  const pngs = new Map();
  for (const size of [16, 32, 48, 64]) {
    const name = `favicon-${size}x${size}.png`;
    const png = await readFile(new URL(`favicon/${name}`, brandRoot)).catch(() => null);
    if (!png) throw new Error(`${name} is missing. Run pnpm brand:sync.`);
    const { format, width, height, hasAlpha } = await sharp(png).metadata();
    if (format !== 'png' || width !== size || height !== size || !hasAlpha) {
      throw new Error(`${name} must be a ${size}x${size} PNG with alpha. Run pnpm brand:sync.`);
    }
    pngs.set(size, png);
  }
  const ico = await readFile(new URL('favicon/favicon.ico', brandRoot)).catch(() => null);
  if (!ico) throw new Error('favicon.ico is missing. Run pnpm brand:sync.');
  const sizes = [16, 32, 48];
  if (ico.readUInt16LE(2) !== 1 || ico.readUInt16LE(4) !== sizes.length) {
    throw new Error('favicon.ico must contain exactly the 16/32/48px frames. Run pnpm brand:sync.');
  }
  sizes.forEach((size, i) => {
    const entry = 6 + 16 * i;
    const offset = ico.readUInt32LE(entry + 12);
    const frame = ico.subarray(offset, offset + ico.readUInt32LE(entry + 8));
    if (ico[entry] !== size || !frame.equals(pngs.get(size))) {
      throw new Error(`favicon.ico ${size}px frame is stale. Run pnpm brand:sync.`);
    }
  });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await generateFavicons(process.argv.includes('--check'));
}
