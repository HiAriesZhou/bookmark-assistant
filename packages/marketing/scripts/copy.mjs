import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { marketingContentSchema, policySchema } from '../schemas/marketing-content.mjs';

const marketingRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = path.resolve(marketingRoot, '../..');
const mode = process.argv.includes('--write') ? 'write' : 'check';

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function stableJson(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function expectedStoreCopy(copy) {
  const claims = copy.releasedClaims.map((claim) => `- ${claim.text}`).join('\n');
  const screenshots = copy.screenshots
    .map((shot, index) => {
      const gate = shot.status === 'feature-gated' ? ` [BLOCKED: ${shot.gate}]` : '';
      return `${index + 1}. ${shot.headline}${gate}\n   ${shot.body}`;
    })
    .join('\n');
  const blocked = copy.screenshots.some((shot) => shot.status === 'feature-gated');
  return `<!-- Generated by packages/marketing/scripts/copy.mjs. Do not edit. -->\n\n# ${copy.extensionName}\n\nPublication status: ${blocked ? 'BLOCKED — feature-gated copy is present' : 'READY FOR HUMAN REVIEW'}\n\n## Short description\n\n${copy.shortDescription}\n\n## Long description\n\n${copy.longDescription}\n\n## Released claims\n\n${claims}\n\n## Screenshot captions\n\n${screenshots}\n`;
}

function websiteModule(copies) {
  const localized = Object.fromEntries(
    [...copies].map(([locale, copy]) => [
      locale,
      {
        productName: copy.productName,
        ctas: copy.ctas,
        ...copy.website,
      },
    ])
  );
  return `// Generated by packages/marketing/scripts/copy.mjs. Do not edit.\nexport const marketingCopy = ${JSON.stringify(localized, null, 2)} as const;\n\nexport type WebsiteLocale = keyof typeof marketingCopy;\nexport type WebsiteCopy = (typeof marketingCopy)[WebsiteLocale];\n`;
}

function assertOrWrite(file, expected, label) {
  if (mode === 'write') {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, expected);
    return;
  }
  const actual = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
  if (actual !== expected) {
    throw new Error(`${label} is missing or has drifted. Run pnpm marketing:copy:sync.`);
  }
}

const policy = policySchema.parse(readJson(path.join(marketingRoot, 'content/policy.json')));
const brand = readJson(path.join(repoRoot, 'packages/shared/brand.json'));
const copies = new Map(
  policy.marketingLocales.map((locale) => {
    const copy = marketingContentSchema.parse(
      readJson(path.join(marketingRoot, `content/${locale}.json`))
    );
    if (copy.locale !== locale) throw new Error(`Locale mismatch in ${locale}.json`);
    return [locale, copy];
  })
);

const reference = copies.get('en');
for (const [locale, copy] of copies) {
  if (copy.productName !== brand.name) {
    throw new Error(`${locale} productName must match packages/shared/brand.json`);
  }
}
const referenceClaimIds = reference.releasedClaims.map(({ id }) => id).sort();
const referenceGatedIds = reference.featureGatedClaims.map(({ id }) => id).sort();
for (const [locale, copy] of copies) {
  const screenshotIds = copy.screenshots.map(({ id }) => id);
  if (JSON.stringify(screenshotIds) !== JSON.stringify(policy.requiredScreenshotIds)) {
    throw new Error(`${locale} screenshot IDs or order do not match policy.`);
  }
  if (
    JSON.stringify(copy.releasedClaims.map(({ id }) => id).sort()) !==
    JSON.stringify(referenceClaimIds)
  ) {
    throw new Error(`${locale} released claim IDs do not match English.`);
  }
  if (
    JSON.stringify(copy.featureGatedClaims.map(({ id }) => id).sort()) !==
    JSON.stringify(referenceGatedIds)
  ) {
    throw new Error(`${locale} gated claim IDs do not match English.`);
  }
  const publicText = JSON.stringify(copy);
  for (const source of policy.forbiddenPublicClaimPatterns) {
    if (new RegExp(source, 'iu').test(publicText)) {
      throw new Error(`${locale} contains forbidden public claim pattern: ${source}`);
    }
  }
}

const extensionLocalesRoot = path.join(repoRoot, 'packages/extension/_locales');
for (const locale of policy.runtimeLocales) {
  const file = path.join(extensionLocalesRoot, locale, 'messages.json');
  if (!fs.existsSync(file)) throw new Error(`Missing runtime locale: ${locale}`);
}

for (const [marketingLocale, extensionLocale] of Object.entries(policy.extensionLocaleMap)) {
  const copy = copies.get(marketingLocale);
  const file = path.join(extensionLocalesRoot, extensionLocale, 'messages.json');
  const catalog = readJson(file);
  catalog.appName = { ...catalog.appName, message: copy.extensionName };
  catalog.appDesc = { ...catalog.appDesc, message: copy.shortDescription };
  catalog.extensionTitle = { ...catalog.extensionTitle, message: copy.extensionTitle };
  assertOrWrite(file, stableJson(catalog), `${extensionLocale} canonical extension messages`);
  assertOrWrite(
    path.join(marketingRoot, `store-copy/${marketingLocale}.md`),
    expectedStoreCopy(copy),
    `${marketingLocale} generated store copy`
  );
}

const manifestFile = path.join(repoRoot, 'packages/extension/public/manifest.json');
const manifest = readJson(manifestFile);
manifest.name = '__MSG_appName__';
manifest.description = '__MSG_appDesc__';
manifest.default_locale = 'en';
assertOrWrite(manifestFile, stableJson(manifest), 'extension manifest marketing fields');
const extensionPackageFile = path.join(repoRoot, 'packages/extension/package.json');
const extensionPackage = readJson(extensionPackageFile);
extensionPackage.description = reference.shortDescription;
assertOrWrite(extensionPackageFile, stableJson(extensionPackage), 'extension package description');
assertOrWrite(
  path.join(repoRoot, 'packages/website/lib/marketing-copy.generated.ts'),
  websiteModule(copies),
  'website canonical marketing module'
);

const websitePublicTargets = [
  path.join(repoRoot, 'packages/website/app'),
  path.join(repoRoot, 'packages/website/components'),
  path.join(repoRoot, 'packages/website/lib/marketing-copy.generated.ts'),
];
for (const target of websitePublicTargets) {
  const files = fs.statSync(target).isDirectory()
    ? fs
        .readdirSync(target, { recursive: true })
        .map(String)
        .filter((file) => /\.(ts|tsx)$/.test(file))
        .map((file) => path.join(target, file))
    : [target];
  for (const file of files) {
    const text = fs.readFileSync(file, 'utf8');
    for (const source of policy.forbiddenPublicClaimPatterns) {
      if (new RegExp(source, 'iu').test(text)) {
        throw new Error(
          `${path.relative(repoRoot, file)} contains forbidden public claim pattern: ${source}`
        );
      }
    }
  }
}

console.log(
  `Canonical marketing copy ${mode === 'write' ? 'synchronized' : 'validated'} for ${policy.marketingLocales.join(', ')}.`
);
